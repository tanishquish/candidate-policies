def build(T, Q, src, cand):
    out = []
    for e in EXTRA:
        statewide = e["office"] != "State Senate"
        sources = []
        if statewide:
            ballot_key = GREEN[0]
            sources.append(src(*GREEN))
        else:
            ballot_key = SENATE_SRC[0]
            sources.append(src(*SENATE_SRC))
        sources.append(src("bp", f"Ballotpedia: {e['name']}", e["bp"]))
        race = e["office"] if statewide else f"State Senate District {e['district']}"
        who = "the incumbent" if e["incumbent"] else "a candidate"
        overview = [[T(f"{e['name']} is {who} on the November 3, 2026 ballot for {race}, running as: {e['ticket']}.", ballot_key)]]
        if e.get("survey") and len(e["survey"]) <= 260 and e["survey"].rstrip().endswith((".", "!", "?")):
            overview.append([T(f"In a Ballotpedia Candidate Connection survey answered in {e['surveyYear']}, they wrote: "), Q(e["survey"], "bp")])
        c = cand(
            id=e["id"], name=e["name"], party=e["party"], ticket=e["ticket"], office=e["office"],
            district=e["district"], website=e["website"], reviewed=None, sources=sources,
            overview=overview, incumbent=e["incumbent"], unreviewed=True, accessed="2026-10-22",
        )
        if e.get("photo"):
            c["photo"] = e["photo"]; c["photoSource"] = e["photoSource"]
            c["photoYear"] = None; c["photoBasis"] = None
        out.append(c)
    return out
